#!/usr/bin/env python3
"""Copy the entry image to the output directory.

The image is drawn by generate.py and committed as entry.png; this program
reproduces it deterministically by copying the bytes, so both runs of the
entry write exactly the same file.
"""

import os
import shutil


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "entry.png")
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "entry.png")
    shutil.copyfile(src, dst)
    # fail loudly rather than silently shipping a partial copy
    if os.path.getsize(dst) != os.path.getsize(src):
        raise SystemExit("entry.png copy is incomplete")


if __name__ == "__main__":
    main()
